"""Generate compose.yaml + compose-topology.yaml for N edge workers (A1..AN) -> one sink worker (B).

Reads data/schema.json (written by embed.py), so the NebulaStream schema, the CSV columns and the
reference vector for B's score always come from the same place.

  A1..AN : File source each (data/worker_XX.csv), downstream -> B
  B      : computes SCORE = dot(embedding, reference) (= cosine, all vectors are unit length)
           and writes WORKER_ID, TS, SCORE, EMB_* to output/results.csv

Example:
  python scripts/gen_topology.py --workers 3
"""
import argparse
import json
from pathlib import Path

# Pinned by multi-arch digest (nightly of 2026-11-09); same build on the Mac (arm64) and server (x64).
WORKER_IMAGE = "nebulastream/nes-worker@sha256:314e78619f10065f58f7d2b942f0b4fa80895abf45479f5568048497abe7c61c"
CLI_IMAGE = "nebulastream/nes-cli@sha256:9a0f08a2afb072118dae67846087e6a885e4876cfdc83a7509135fb2836b50eb"

HEADER = "# GENERATED by scripts/gen_topology.py -- do not edit by hand, re-run the script instead.\n"


def a_name(i):
    return f"worker-a{i}"


def schema_block(columns, indent):
    return "\n".join(f"{indent}- name: {c['name']}\n{indent}  type: {c['type']}" for c in columns)


def score_expression(emb_cols, reference):
    # A single expression compiles up to 64 terms; 128+ fails ("Stack is too deep", see CLAUDE.md).
    if len(emb_cols) > 64:
        raise SystemExit(f"{len(emb_cols)} dims: single-expression SQL score only works up to 64")
    return " + ".join(f"{c} * FLOAT32({r:.6f})" for c, r in zip(emb_cols, reference))


def topology(workers, schema, edge_max_ops):
    cols = schema["columns"]
    emb_cols = [c["name"] for c in cols if c["name"].startswith("EMB_")]
    out_cols = cols[:2] + [{"name": "SCORE", "type": "FLOAT32"}] + cols[2:]
    select = ", ".join(["WORKER_ID", "TS", f"{score_expression(emb_cols, schema['reference'])} AS SCORE"]
                       + emb_cols)

    physical = "\n".join(f"""  - logical: EMBEDDINGS
    host: {a_name(i)}:8080
    type: File
    parser_config:
      type: CSV
      field_delimiter: ","
    source_config:
      file_path: /data/worker_{i:02d}.csv""" for i in range(1, workers + 1))

    worker_entries = "\n".join(f"""  - host: {a_name(i)}:8080
    data_address: {a_name(i)}:9090
    max_operators: {edge_max_ops}
    downstream: [ worker-b:8080 ]""" for i in range(1, workers + 1))

    return f"""{HEADER}# {workers} edge workers -> worker-b. Reference: {schema['reference_group']} centroid, {schema['dims']} dims.
# max_operators: {edge_max_ops} on the edge workers {'forces the SCORE projection onto worker-b' if edge_max_ops == 0 else 'lets the optimiser place the SCORE at the edge'}.
query: |
  SELECT {select}
  FROM EMBEDDINGS
  INTO RESULTS

sinks:
  - name: RESULTS
    host: worker-b:8080
    schema:
{schema_block(out_cols, '      ')}
    type: File
    config:
      output_format: CSV
      file_path: /output/results.csv
      append: false

logical:
  - name: EMBEDDINGS
    schema:
{schema_block(cols, '      ')}

physical:
{physical}

workers:
{worker_entries}
  - host: worker-b:8080
    data_address: worker-b:9090
    max_operators: 10000
"""


def compose(workers, data_dir):
    edge = "\n".join(f"""  {a_name(i)}:
    image: {WORKER_IMAGE}
    hostname: {a_name(i)}
    volumes:
      - ./{data_dir}:/data:ro    # input CSVs (read-only)
    command: ["--", "--grpc=0.0.0.0:8080", "--data_address={a_name(i)}:9090"]
    tty: true
    stdin_open: true
""" for i in range(1, workers + 1))
    deps = "\n".join(f"      - {a_name(i)}" for i in range(1, workers + 1))
    return f"""{HEADER}# {workers} edge workers -> worker-b. Only worker-b mounts ./output, so every row in
# output/results.csv has travelled over the network from an edge worker.
services:
{edge}
  worker-b:
    image: {WORKER_IMAGE}
    hostname: worker-b
    volumes:
      - ./output:/output
    command: ["--", "--grpc=0.0.0.0:8080", "--data_address=worker-b:9090"]
    tty: true
    stdin_open: true

  nes-cli:
    image: {CLI_IMAGE}
    depends_on:
      - worker-b
{deps}
    volumes:
      - .:/catalog:ro
      - nes-cli-state:/state   # query-id -> worker mapping, needed for later `status`/`stop`
    command: ["-t", "/catalog/compose-topology.yaml", "start"]

volumes:
  nes-cli-state:
"""


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--workers", type=int, default=None,
                   help="number of edge workers (default: all workers in schema.json; may be fewer)")
    p.add_argument("--data-dir", default="data", help="directory with schema.json and worker_XX.csv")
    p.add_argument("--score-at-edge", action="store_true",
                   help="let the optimiser compute SCORE on the edge workers (default: on worker-b)")
    p.add_argument("--out-dir", default=".")
    a = p.parse_args()

    schema = json.loads((Path(a.data_dir) / "schema.json").read_text())
    available = len(schema["workers"])
    workers = a.workers or available
    if not 1 <= workers <= available:
        raise SystemExit(f"--workers must be 1..{available} (schema.json has {available}); re-run embed.py")
    for i in range(1, workers + 1):
        if not (Path(a.data_dir) / f"worker_{i:02d}.csv").exists():
            raise SystemExit(f"missing {a.data_dir}/worker_{i:02d}.csv")

    out = Path(a.out_dir)
    (out / "compose-topology.yaml").write_text(topology(workers, schema, 10000 if a.score_at_edge else 0))
    (out / "compose.yaml").write_text(compose(workers, a.data_dir))
    print(f"wrote compose.yaml + compose-topology.yaml: {workers} edge workers -> worker-b, "
          f"{schema['dims']} dims, score on {'edge' if a.score_at_edge else 'worker-b'}")
    for i in range(1, workers + 1):
        print(f"  {a_name(i)}: {', '.join(schema['workers'][str(i)])}")


if __name__ == "__main__":
    main()
